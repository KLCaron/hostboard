test('real metric issues retain thresholds, recovery history and container investigations',async({page,request},info)=>{
  const fleet=await (await request.get('/api/fleet')).json();
  const current=await (await request.get(`/api/hosts/${fleet.hosts[0].id}/alerts`)).json();
  await page.goto('/');
  await page.getByRole('link',{name:'Issues',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Active issues',exact:true})).toBeVisible();
  await page.getByLabel('Issue type',{exact:true}).selectOption('metric');
  await page.getByLabel('Host',{exact:true}).selectOption(fleet.hosts[0].id);
  const dialog=page.getByRole('dialog');
  if(current.active.length) {
    await page.locator('.issue-results').getByRole('button').filter({hasText:current.active[0].summary}).first().click();
    await expect(dialog.getByText('Warning rule:',{exact:false})).toBeVisible();
    if(current.active[0].warning) await expect(dialog.getByText('Warning rule:',{exact:false})).toContainText(current.active[0].warning);
    await expect(dialog.getByText(/Available retention:|no longer collected/)).toBeVisible();
    await page.getByRole('button',{name:'Close investigation'}).click();
  } else await expect(page.getByText('No active issues match these filters.')).toBeVisible();
  await page.getByRole('tab',{name:'History',exact:true}).click();
  if(current.resolved.length) {
    const resolved=page.locator('.issue-results').getByRole('button').filter({hasText:current.resolved[0].summary}).first();
    await expect(resolved).toBeVisible();await resolved.click();
    await expect(dialog.getByText('before clearing',{exact:false})).toBeVisible();
    await expect(dialog.getByText(/Available retention:|no longer collected/)).toBeVisible();
    await page.keyboard.press('Escape');
  } else await expect(page.getByText('No historical issues match these filters.')).toBeVisible();
  const bookmarked=current.resolved[0]||current.active[0];
  if(bookmarked){
    await page.goto(`/#alert=${fleet.hosts[0].id}:${encodeURIComponent(bookmarked.id)}`);
    await expect(dialog).toBeVisible();
    await expect(dialog.getByText('Warning rule:',{exact:false})).toBeVisible();
    await page.reload();
    await expect(dialog).toBeVisible();
    await page.getByRole('button',{name:'Close investigation'}).click();
  }
  await page.getByRole('link',{name:'Services',exact:true}).click();
  await page.locator('.services-panel>summary').click();
  await page.locator('.service-list>details>summary').first().click();
  await expect(page.locator('.service-list').getByText(/Application availability: not independently checked/).first()).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:`.ai-local/${info.project.name}-alerts-services.png`,fullPage:true});
});

test('API validation and visible connection failures without invented readings',async({page,request})=>{
  const fleet=await (await request.get('/api/fleet')).json();
  const id=fleet.hosts[0].id;
  expect((await request.get('/api/hosts/unknown/alerts')).status()).toBe(404);
  expect((await request.get(`/api/hosts/${id}/metric-history?chart=system.cpu&after=x&before=2`)).status()).toBe(400);
  const now=Math.floor(Date.now()/1000);
  expect((await request.get(`/api/hosts/${id}/metric-history?chart=nonexistent&after=${now-3600}&before=${now}`)).status()).toBe(404);
  // Fault injection aborts requests; all successful metrics still come from real Agents.
  await page.route('**/api/fleet',route=>route.abort());
  await page.goto('/');
  await expect(page.getByRole('alert')).toContainText('Cannot refresh dashboard');
  await page.unroute('**/api/fleet');
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await expect(page.locator('.host-card').first().getByText('Online',{exact:true})).toBeVisible();
  await page.route('**/metric-history?**',route=>route.abort());
  await page.locator('.host-card').first().getByRole('button',{name:'Explore host'}).click();
  await expect(page.locator('.host-card').first().getByRole('alert')).toBeVisible();
  await expect(page.locator('.host-card').first().getByRole('button',{name:'Retry'})).toBeVisible();
});

test('pause freezes historical requests while resume restores a moving window',async({page,request})=>{
  const fleet=await (await request.get('/api/fleet')).json();
  await page.goto(`/#host=${fleet.hosts[0].id}`);
  const explorer=page.locator('.host-card.expanded').getByRole('region',{name:'Metric investigation'});
  await expect(explorer.getByText('Available retention:',{exact:false})).toBeVisible();
  await explorer.getByRole('button',{name:'Pause',exact:true}).click();
  await expect(explorer.getByText('Available retention:',{exact:false})).toBeVisible();
  await page.clock.install();
  const requests:string[]=[];
  page.on('request',r=>{if(r.url().includes('/metric-history?'))requests.push(r.url());});
  await page.clock.fastForward(35000);
  expect(requests).toEqual([]);
  const resumedRequest=page.waitForRequest(r=>r.url().includes('/metric-history?'));
  await explorer.getByRole('button',{name:'Resume live'}).click();
  await resumedRequest;
  await expect(explorer.getByRole('button',{name:'Pause',exact:true})).toBeVisible();
});

test('dragging the plot and timeline selects a real range and zoom queries that range',async({page,request},info)=>{
  const fleet=await (await request.get('/api/fleet')).json();
  await page.goto(`/#host=${fleet.hosts[0].id}`);
  const explorer=page.locator('.host-card.expanded').getByRole('region',{name:'Metric investigation'});
  const response=page.waitForResponse(r=>{if(!r.url().includes('/metric-history?')||!r.ok())return false;const q=new URL(r.url()).searchParams;return Number(q.get('before'))-Number(q.get('after'))===900;});
  await explorer.getByRole('button',{name:'15m',exact:true}).click();
  const history=await (await response).json();
  await expect(explorer.getByText('Available retention:',{exact:false})).toBeVisible();
  const plot=explorer.locator('.selectable-chart');await plot.scrollIntoViewIfNeeded();
  const box=(await plot.boundingBox())!;
  const left=box.x+54,width=box.width-66,y=box.y+box.height/2;
  await page.mouse.move(left+width*.2,y);await page.mouse.down();
  await page.mouse.move(left+width*.7,y,{steps:12});await page.mouse.up();
  await expect(explorer.getByRole('status',{name:'Selected time window'})).toContainText('Selected:');
  await expect(explorer.getByRole('button',{name:'Resume live'})).toBeVisible();
  const zoom=explorer.getByRole('button',{name:'Zoom to brushed selection'});
  await expect(zoom).toBeEnabled();
  const start=explorer.getByRole('slider',{name:'Selection start'}),end=explorer.getByRole('slider',{name:'Selection end'});
  await page.clock.install();
  const backgroundRequests:string[]=[];
  page.on('request',r=>{if(r.url().includes('/metric-history?'))backgroundRequests.push(r.url());});
  await page.clock.fastForward(35000);
  expect(backgroundRequests).toEqual([]);
  const initialStart=Number(await start.getAttribute('aria-valuenow'));
  expect(initialStart).toBeGreaterThan(0);
  expect(Number(await end.getAttribute('aria-valuenow'))).toBeLessThan(history.points.length-1);
  // Both handles support keyboard adjustment in addition to pointer dragging.
  await start.focus();await page.keyboard.press('ArrowRight');
  await expect.poll(async()=>Number(await start.getAttribute('aria-valuenow'))).toBe(initialStart+1);
  const startIndex=Number(await start.getAttribute('aria-valuenow')),endIndex=Number(await end.getAttribute('aria-valuenow'));
  const zoomRequest=page.waitForRequest(r=>r.url().includes('/metric-history?'));
  await zoom.click();const url=new URL((await zoomRequest).url());
  expect(Number(url.searchParams.get('after'))).toBe(history.points[startIndex].time);
  expect(Number(url.searchParams.get('before'))).toBe(history.points[endIndex].time);
  await expect(explorer.getByText('Available retention:',{exact:false})).toBeVisible();
  await expect(zoom).toBeDisabled();
  // The timeline also accepts a new selection anywhere on its track, right-to-left.
  const track=explorer.locator('.history-brush-track');await track.scrollIntoViewIfNeeded();
  const b=(await track.boundingBox())!;
  await page.mouse.move(b.x+b.width*.8,b.y+b.height/2);await page.mouse.down();
  await page.mouse.move(b.x+b.width*.3,b.y+b.height/2,{steps:10});await page.mouse.up();
  await expect(zoom).toBeEnabled();
  await end.scrollIntoViewIfNeeded();
  const handle=(await end.boundingBox())!;const previousEnd=Number(await end.getAttribute('aria-valuenow'));
  await page.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await page.mouse.down();
  await page.mouse.move(handle.x+handle.width/2-b.width*.1,handle.y+handle.height/2,{steps:8});await page.mouse.up();
  await expect.poll(async()=>Number(await end.getAttribute('aria-valuenow'))).toBeLessThan(previousEnd);
  await page.screenshot({path:`.ai-local/${info.project.name}-brush-selection.png`});
  await explorer.getByRole('button',{name:'Clear selection'}).click();await expect(zoom).toBeDisabled();
});
