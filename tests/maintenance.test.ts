import test from 'node:test';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {mkdtempSync,rmSync,readFileSync,chmodSync,mkdirSync,statSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import {Configuration} from '../server/settings.js';
import {ChecksSchema} from '../server/check-config.js';
test('standalone SQLite backup restores from read-only media and stdin, rejects newer schemas without replacing live data',t=>{
  const dir=mkdtempSync(path.join(tmpdir(),'hostboard-recovery-')),media=path.join(dir,'media');mkdirSync(media);
  t.after(()=>{chmodSync(media,0o700);rmSync(dir,{recursive:true,force:true});});
  const live=path.join(dir,'monitor.sqlite'),file=path.join(media,'backup.sqlite');
  const store=new Configuration(live,ChecksSchema.parse({}));
  const run=(command:string,source:string,input?:Buffer)=>spawnSync(process.execPath,['--import','tsx','server/maintenance.ts',command,source],{env:{...process.env,HOSTBOARD_DB:live},input,encoding:'utf8'});
  let result=run('backup',file);assert.equal(result.status,0,result.stderr);
  assert.equal(statSync(file).mode&0o077,0);
  const backup=new DatabaseSync(file,{readOnly:true});
  assert.equal(backup.prepare('PRAGMA journal_mode').get()!.journal_mode,'delete');backup.close();
  const settings=store.settings();settings.general.temperature='F';store.saveSettings(settings);store.db.close();
  chmodSync(file,0o400);chmodSync(media,0o500);
  result=run('restore',file);assert.equal(result.status,0,result.stderr);
  let restored=new Configuration(live,ChecksSchema.parse({}));assert.equal(restored.settings().general.temperature,'C');restored.db.close();
  result=run('restore','-',readFileSync(file));assert.equal(result.status,0,result.stderr);
  const future=path.join(dir,'future.sqlite'),f=new DatabaseSync(future);f.exec('PRAGMA user_version=4');f.close();
  const before=readFileSync(live);
  result=run('restore',future);assert.notEqual(result.status,0);assert.deepEqual(readFileSync(live),before);
  restored=new Configuration(live,ChecksSchema.parse({}));assert.equal(restored.settings().general.temperature,'C');restored.db.close();
});
